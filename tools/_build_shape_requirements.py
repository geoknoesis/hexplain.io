"""Generate specification/req/requirements.ttl: one requirement per node shape of the family.

Every named sh:NodeShape of every family module gets one reqs:ShapeRequirement, derived from the
shape and from nothing else:

* its statement is the definition the shape's documentation gives (the shape's skos:definition,
  generated into the module's <module>-doc.ttl, or the rdfs:comment its author wrote);
* dcterms:references names the shape;
* req:fromStandard is the label of the module that publishes the shape, WITHOUT its version, and
  req:requirementId is req-shape-<prefix>-<ShapeLocalName>, always with the prefix: the pair is
  the requirement's identity, so it must survive a version bump and the arrival of a second
  module that reuses the local name;
* req:discrepancyType classifies the shape by its constraints (classification(), below).

Run with --write after the module annotations are current (`_build_term_reference.py --enrich`),
then enrich once more so that requirements-doc.ttl follows; --check (the default) compares and
writes nothing. tools/test_shape_requirements.py holds the result to the shapes.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

from _family import canonical_files
from _reference import load, stated_definition
from rdflib import OWL, RDF, RDFS, BNode, Graph, Literal, Namespace, URIRef
from rdflib.collection import Collection

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "specification"
TARGET = "req/requirements.ttl"
ONTOLOGY = "https://hexplain.io/ns/req/requirements"
SH = Namespace("http://www.w3.org/ns/shacl#")
REQ = Namespace("https://hexplain.io/ns/req#")
DCT_MODIFIED = URIRef("http://purl.org/dc/terms/modified")
VERSIONED = re.compile(r"\d+(\.\d+)+\s*$")
LOGICAL = (SH["or"], SH.xone, SH["and"], SH["not"])
#: Constraints that relate one property to another, or a focus node to the rest of the graph.
RELATING = (SH.sparql, SH.rule, SH.equals, SH.disjoint, SH.lessThan, SH.lessThanOrEquals, SH.qualifiedValueShape)

HEADER = """\
# Hexplain Specification Requirements 1.0 -- the requirements the family's own node shapes enforce
# Generated by tools/_build_shape_requirements.py --write; do not edit. One reqs:ShapeRequirement
# per named node shape of every family module, derived from the shape: its statement is the
# shape's documented definition, its identifier req-shape-<prefix>-<ShapeLocalName>, its source
# the module's label without a version. tools/test_shape_requirements.py keeps the two in step.
"""
STANDARD_PREFIXES = {
    "owl": str(OWL),
    "rdfs": str(RDFS),
    "xsd": "http://www.w3.org/2001/XMLSchema#",
    "dcterms": "http://purl.org/dc/terms/",
    "vann": "http://purl.org/vocab/vann/",
    "skos": "http://www.w3.org/2004/02/skos/core#",
}
ONTOLOGY_COMMENT = (
    "The normative requirements that the specification's own SHACL node shapes enforce on a description, each a "
    "req:Requirement citing its shape with dcterms:references: one for every named node shape of every module of "
    "the family. The source document of a requirement is the vocabulary module that publishes the shape, named "
    "without its version; its identifier is req-shape-<prefix>-<ShapeLocalName>. The pair therefore survives a new "
    "version of the module and never changes meaning (tools/_requirement_ids.py states the same rule for prose "
    "requirements). A conformance profile may cite these requirements with conf:satisfies exactly as it cites a "
    "format standard's."
)
ONTOLOGY_NOTE = (
    "Load with a conformance profile that attributes a description-level finding to the shape requirement it "
    "breaks, or to read which requirement a shape stands for. It mints no shapes and no new constraints: every "
    "statement restates a shape's documented definition, and the file is regenerated when a shape changes."
)
CLASS_BLOCK = """\
# A requirement of the specification itself, as opposed to one a conformance profile declares
# for a format standard. A subclass, and the individuals are typed with it alone: conf:RunShape
# demands an outcome for every resource typed req:Requirement in the graph it validates (a run
# report with its rule set), and the family's own requirements are not part of any rule set.
# Under RDFS entailment each is a req:Requirement; req:RequirementShape still validates each
# through its activation by req:requirementId and the other requirement properties.
reqs:ShapeRequirement a owl:Class ; rdfs:subClassOf req:Requirement ; rdfs:label "Shape Requirement"@en ;
    rdfs:isDefinedBy <https://hexplain.io/ns/req/requirements> ;
    rdfs:comment "A req:Requirement that one of the specification's own SHACL node shapes enforces on a \
description, named by dcterms:references. Its req:fromStandard is the label of the vocabulary module publishing the \
shape, without a version, and its req:requirementId is req-shape-<prefix>-<ShapeLocalName>. Its req:discrepancyType \
is derived from the shape: req:Syntactic when every constraint checks one property's values on their own (datatype, \
node kind, class, enumeration, pattern, bounds, cardinality), req:Semantic when a constraint relates properties or \
nodes to one another (a logical combination of property constraints, a property pair, a qualified count or a SPARQL \
constraint), so that each value may be well formed while the description as a whole is not."@en ;
    skos:scopeNote "Assert on the family's own requirements only; a conformance profile's requirements for a \
format standard are plain req:Requirement resources. A conf:Constraint may cite a shape requirement with \
conf:satisfies like any other."@en .
"""


def namespaces() -> dict[str, str]:
    """Namespace IRI -> prefix, from the family's authoritative table."""
    rows = json.loads((SPEC / "family.json").read_text(encoding="utf-8"))["namespaces"]
    return {row["namespace"]: row["prefix"] for row in rows}


def _relates(g: Graph, node: Any, seen: set[Any]) -> bool:
    """Whether a shape node, or anything nested under it, relates properties or nodes to one another."""
    if node in seen:
        return False
    seen.add(node)
    if any((node, predicate, None) in g for predicate in RELATING):
        return True
    for operator in LOGICAL:
        for value in g.objects(node, operator):
            branches = [value] if operator == SH["not"] else list(Collection(g, value))
            if any(_states_property(g, branch) or _relates(g, branch, seen) for branch in branches):
                return True
    return any(_relates(g, nested, seen) for nested in g.objects(node, SH.property)) or any(
        _relates(g, nested, seen) for nested in g.objects(node, SH.node) if isinstance(nested, BNode)
    )


def _states_property(g: Graph, branch: Any) -> bool:
    """A logical branch that constrains a property of the focus node rather than the value itself."""
    return (branch, SH.property, None) in g or (branch, SH.path, None) in g


def classification(g: Graph, shape: Any) -> URIRef:
    """req:Semantic when the shape relates properties or nodes to one another, else req:Syntactic.

    A logical operator over value constraints alone (the datatype union of an integer value shape,
    `sh:not [ sh:pattern ... ]` on one property) still checks one property's values on their own.
    """
    return REQ.Semantic if _relates(g, shape, set()) else REQ.Syntactic


def module_rows(rel: str, prefixes: dict[str, str]) -> list[dict[str, Any]]:
    """One row per named node shape the canonical module ``rel`` declares."""
    path = Path("specification") / rel
    own = load([path], base=True)
    documented = load([path])
    ontology = next(iter(own.subjects(RDF.type, OWL.Ontology)))
    standard = str(
        next(o for o in own.objects(ontology, RDFS.label) if isinstance(o, Literal) and o.language in ("en", None))
    )
    if VERSIONED.search(standard):
        raise ValueError(f"{rel}: the ontology label '{standard}' ends in a version; identity must not carry one")
    rows = []
    for shape in sorted(s for s in set(own.subjects(RDF.type, SH.NodeShape)) if isinstance(s, URIRef)):
        namespace, local = str(shape).rsplit("#", 1)
        prefix = prefixes[namespace + "#"]
        statement = stated_definition(documented, shape)
        if statement is None:
            raise ValueError(f"{prefix}:{local} has no documented definition; run _build_term_reference.py --enrich")
        rows.append(
            {
                "id": f"req-shape-{prefix}-{local}",
                "curie": f"{prefix}:{local}",
                "prefix": prefix,
                "namespace": namespace + "#",
                "ontology": str(ontology),
                "standard": standard,
                "modified": str(own.value(ontology, DCT_MODIFIED)),
                "statement": str(statement),
                "type": "req:" + str(classification(own, shape)).rsplit("#", 1)[1],
            }
        )
    return rows


def rows() -> list[dict[str, Any]]:
    """Every shape requirement of the family, ordered by identifier."""
    prefixes = namespaces()
    found = [row for rel in canonical_files(SPEC) if rel != TARGET for row in module_rows(rel, prefixes)]
    identifiers = [row["id"] for row in found]
    if len(set(identifiers)) != len(identifiers):
        raise ValueError("two node shapes yield one requirement identifier")
    return sorted(found, key=lambda row: row["id"])


def individual(row: dict[str, Any]) -> str:
    def literal(text: str, lang: str | None = None) -> str:
        return Literal(text, lang=lang).n3()

    comment = (
        f"The requirement {row['curie']} enforces on a description; a description that this shape reports does "
        "not satisfy it."
    )
    return (
        f"reqs:{row['id']} a owl:NamedIndividual , reqs:ShapeRequirement ;\n"
        f"    rdfs:label {literal('Requirement of ' + row['curie'], 'en')} ;\n"
        f"    rdfs:isDefinedBy <{ONTOLOGY}> ;\n"
        f"    rdfs:comment {literal(comment, 'en')} ;\n"
        f"    req:requirementId {literal(row['id'])} ;\n"
        f"    req:fromStandard {literal(row['standard'])} ;\n"
        f"    req:statement {literal(row['statement'], 'en')} ;\n"
        f"    req:discrepancyType {row['type']} ;\n"
        f"    dcterms:references {row['curie']} .\n"
    )


def render() -> str:
    found = rows()
    prefixes = {"reqs": ONTOLOGY + "#", "req": str(REQ), **{row["prefix"]: row["namespace"] for row in found}}
    prefixes.update(STANDARD_PREFIXES)
    imports = sorted({"https://hexplain.io/ns/req", *(row["ontology"] for row in found)})
    # The module is derived from the modules it imports, so it was last modified when they were.
    modified = max(row["modified"] for row in found)
    head = "".join(f"@prefix {p}: <{ns}> .\n" for p, ns in sorted(prefixes.items()))
    ontology = (
        f"<{ONTOLOGY}> a owl:Ontology ;\n"
        f"    rdfs:seeAlso <https://hexplain.io/specification/req/requirements-doc.ttl> ;\n"
        f'    owl:versionIRI <{ONTOLOGY}/1.0> ; owl:versionInfo "1.0" ;\n'
        f'    dcterms:modified "{modified}"^^xsd:date ; dcterms:created "2026-10-12"^^xsd:date ;\n'
        "    dcterms:creator <https://geoknoesis.com> ;\n"
        "    dcterms:license <https://creativecommons.org/licenses/by/4.0/> ;\n"
        "    # req supplies the requirement vocabulary; every module that publishes a node shape is\n"
        "    # imported because a requirement names its shape. The link runs from the requirement to\n"
        "    # the shape because the layering runs the other way: bddo cannot import a module above it.\n"
        "    owl:imports " + " ,\n        ".join(f"<{iri}>" for iri in imports) + " ;\n"
        f'    vann:preferredNamespacePrefix "reqs" ; vann:preferredNamespaceUri "{ONTOLOGY}#" ;\n'
        '    rdfs:label "Hexplain Specification Requirements"@en ;\n'
        f"    rdfs:comment {Literal(ONTOLOGY_COMMENT, lang='en').n3()} ;\n"
        f"    skos:scopeNote {Literal(ONTOLOGY_NOTE, lang='en').n3()} .\n"
    )
    return HEADER + head + "\n" + ontology + "\n" + CLASS_BLOCK + "\n" + "".join(individual(row) for row in found)


def run(write: bool = False) -> int:
    text = render()
    path = SPEC / TARGET
    if write:
        path.write_text(text, encoding="utf-8", newline="\n")
    elif path.read_text(encoding="utf-8") != text:
        raise AssertionError(f"Stale {TARGET}: run python tools/_build_shape_requirements.py --write")
    return text.count(" a owl:NamedIndividual , reqs:ShapeRequirement ;")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="Write the generated module")
    group.add_argument("--check", action="store_true", help="Fail if the module is stale; write nothing (default)")
    args = parser.parse_args()
    print(f"PASS: {run(args.write)} shape requirements {'written' if args.write else 'are current'}")
