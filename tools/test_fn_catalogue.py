"""The function catalogue of specification/fn/index.html is generated from fn.ttl.

The catalogue table was maintained by hand and drifted from the canonical RDF: after the affine
became corner-based, it still said hxf:column and hxf:row round to the nearest cell centre for
asref:PixelCenter. The table is now rendered from each hxf:Function's kind, signature, hxf:reads
and rdfs:comment, and this gate fails when the page differs. It only checks; the section is
regenerated by ``python tools/_build_fn_catalogue.py --write``.
"""

from __future__ import annotations

import sys

from _build_fn_catalogue import expected_page
from _pure_function_contracts import check as check_pure_functions


def main() -> int:
    # The old `--write` habit must not look like a pass that regenerated something.
    assert len(sys.argv) == 1, (
        "this gate takes no arguments and writes nothing; the catalogue is written by "
        "`python tools/_build_fn_catalogue.py --write`"
    )
    text, expected = expected_page()
    if text != expected:
        print(
            "FAIL: the function catalogue of specification/fn/index.html differs from fn.ttl; "
            "run python tools/_build_fn_catalogue.py --write"
        )
        return 1
    calls = check_pure_functions()
    print(f"PASS: current function catalogue; {calls} actual SPARQL function-body probes cover all six pure functions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
